/**
 * @file hid_descriptors.c
 * @brief PocketHID USB HID Composite Report Descriptor Array
 */

#include "hid_descriptors.h"

const uint8_t pockethid_combo_report_descriptor[] = {
    // Report ID 1 — Keyboard (8 byte: modifiers, reserved, 6 keycodes)
    0x05, 0x01, 0x09, 0x06, 0xA1, 0x01, 0x85, 0x01,
    0x05, 0x07, 0x19, 0xE0, 0x29, 0xE7, 0x15, 0x00, 0x25, 0x01,
    0x75, 0x01, 0x95, 0x08, 0x81, 0x02, // 8 modifier bits
    0x95, 0x01, 0x75, 0x08, 0x81, 0x01, // reserved byte
    0x95, 0x06, 0x75, 0x08, 0x15, 0x00, 0x25, 0x65,
    0x05, 0x07, 0x19, 0x00, 0x29, 0x65, 0x81, 0x00, // 6 key array
    0xC0,

    // Report ID 2 — Mouse (4 byte: buttons, dx, dy, wheel)
    0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x85, 0x02, 0x09, 0x01, 0xA1, 0x00,
    0x05, 0x09, 0x19, 0x01, 0x29, 0x03, 0x15, 0x00, 0x25, 0x01,
    0x95, 0x03, 0x75, 0x01, 0x81, 0x02, // 3 buttons
    0x95, 0x01, 0x75, 0x05, 0x81, 0x01, // padding
    0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x09, 0x38,
    0x15, 0x81, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x03, 0x81, 0x06, // X, Y, wheel relative
    0xC0, 0xC0,

    // Report ID 3 — Consumer Control (Media)
    0x05, 0x0C, // Usage Page (Consumer)
    0x09, 0x01, // Usage (Consumer Control)
    0xA1, 0x01, // Collection (Application)
    0x85, 0x03, //   Report ID (3)
    0x15, 0x00, //   Logical Minimum (0)
    0x26, 0xFF, 0x03, // Logical Maximum (0x03FF)
    0x19, 0x00, //   Usage Minimum (0)
    0x2A, 0xFF, 0x03, // Usage Maximum (0x03FF)
    0x95, 0x01, //   Report Count (1)
    0x75, 0x10, //   Report Size (16)
    0x81, 0x00, //   Input (Data, Array)
    0xC0,       // End Collection

    // Report ID 4 — Gamepad (13 bytes: 16 buttons, 1 hat switch, 4 axes, 2 triggers)
    0x05, 0x01, // Usage Page (Generic Desktop)
    0x09, 0x05, // Usage (Gamepad)
    0xA1, 0x01, // Collection (Application)
    0x85, 0x04, //   Report ID (4)
    // 16 Digital Buttons
    0x05, 0x09, //   Usage Page (Button)
    0x19, 0x01, //   Usage Minimum (Button 1)
    0x29, 0x10, //   Usage Maximum (Button 16)
    0x15, 0x00, //   Logical Minimum (0)
    0x25, 0x01, //   Logical Maximum (1)
    0x75, 0x01, //   Report Size (1)
    0x95, 0x10, //   Report Count (16)
    0x81, 0x02, //   Input (Data, Var, Abs)
    // Hat Switch (D-Pad, 4 bits + 4 bits padding = 1 byte)
    0x05, 0x01, //   Usage Page (Generic Desktop)
    0x09, 0x39, //   Usage (Hat switch)
    0x15, 0x01, //   Logical Minimum (1)
    0x25, 0x08, //   Logical Maximum (8)
    0x35, 0x00, //   Physical Minimum (0)
    0x46, 0x3B, 0x01, // Physical Maximum (315)
    0x65, 0x14, //   Unit (Eng Rot: Angular Pos)
    0x75, 0x04, //   Report Size (4)
    0x95, 0x01, //   Report Count (1)
    0x81, 0x42, //   Input (Data, Var, Abs, Null State)
    0x75, 0x04, //   Report Size (4) - padding
    0x95, 0x01, //   Report Count (1)
    0x81, 0x03, //   Input (Const, Var, Abs)
    // Reset Physical Items and Unit
    0x65, 0x00, //   Unit (None)
    0x35, 0x00, //   Physical Minimum (0)
    0x45, 0x00, //   Physical Maximum (0)
    // Left Stick (X, Y) wrapped in Physical Pointer Collection
    0x05, 0x01, //   Usage Page (Generic Desktop)
    0x09, 0x01, //   Usage (Pointer)
    0xA1, 0x00, //   Collection (Physical)
    0x09, 0x30, //     Usage (X)
    0x09, 0x31, //     Usage (Y)
    0x16, 0x00, 0x80, //   Logical Minimum (-32768)
    0x26, 0xFF, 0x7F, //   Logical Maximum (32767)
    0x75, 0x10, //     Report Size (16)
    0x95, 0x02, //     Report Count (2)
    0x81, 0x02, //     Input (Data, Var, Abs)
    0xC0,       //   End Collection (Physical)
    // Right Stick (Z, Rz) wrapped in Physical Pointer Collection
    0x05, 0x01, //   Usage Page (Generic Desktop)
    0x09, 0x01, //   Usage (Pointer)
    0xA1, 0x00, //   Collection (Physical)
    0x09, 0x32, //     Usage (Z)
    0x09, 0x35, //     Usage (Rz)
    0x16, 0x00, 0x80, //   Logical Minimum (-32768)
    0x26, 0xFF, 0x7F, //   Logical Maximum (32767)
    0x75, 0x10, //     Report Size (16)
    0x95, 0x02, //     Report Count (2)
    0x81, 0x02, //     Input (Data, Var, Abs)
    0xC0,       //   End Collection (Physical)
    // 2 Analog Triggers (LT as Rx, RT as Ry: 0..255)
    0x05, 0x01, //   Usage Page (Generic Desktop)
    0x09, 0x33, //   Usage (Rx)
    0x09, 0x34, //   Usage (Ry)
    0x15, 0x00, //   Logical Minimum (0)
    0x26, 0xFF, 0x00, //   Logical Maximum (255)
    0x75, 0x08, //   Report Size (8)
    0x95, 0x02, //   Report Count (2)
    0x81, 0x02, //   Input (Data, Var, Abs)
    0xC0,       // End Collection (Application)

    // Report ID 5 — Digitizer / Absolute Drawing Tablet (5 bytes: Status, X 16-bit, Y 16-bit)
    0x05, 0x0D, // Usage Page (Digitizers)
    0x09, 0x02, // Usage (Pen)
    0xA1, 0x01, // Collection (Application)
    0x85, 0x05, //   Report ID (5)
    0x09, 0x20, //   Usage (Stylus)
    0xA1, 0x00, //   Collection (Physical)
    0x09, 0x42, //     Usage (Tip Switch)
    0x09, 0x32, //     Usage (In Range)
    0x09, 0x44, //     Usage (Barrel Switch)
    0x09, 0x3C, //     Usage (Invert)
    0x09, 0x45, //     Usage (Eraser)
    0x15, 0x00, //     Logical Minimum (0)
    0x25, 0x01, //     Logical Maximum (1)
    0x75, 0x01, //     Report Size (1)
    0x95, 0x05, //     Report Count (5)
    0x81, 0x02, //     Input (Data, Var, Abs)
    0x75, 0x01, //     Report Size (1)
    0x95, 0x03, //     Report Count (3)
    0x81, 0x03, //     Input (Const, Var, Abs) - padding 3 bits
    0x05, 0x01, //     Usage Page (Generic Desktop)
    0x09, 0x30, //     Usage (X)
    0x09, 0x31, //     Usage (Y)
    0x16, 0x00, 0x00, // Logical Minimum (0)
    0x26, 0xFF, 0x7F, // Logical Maximum (32767)
    0x36, 0x00, 0x00, // Physical Minimum (0)
    0x46, 0xFF, 0x7F, // Physical Maximum (32767)
    0x65, 0x00, //     Unit (None)
    0x75, 0x10, //     Report Size (16)
    0x95, 0x02, //     Report Count (2)
    0x81, 0x02, //     Input (Data, Var, Abs)
    0xC0,       //   End Collection (Physical)
    0xC0        // End Collection (Application)
};

const size_t pockethid_combo_report_descriptor_len = sizeof(pockethid_combo_report_descriptor);
